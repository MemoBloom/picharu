import { beforeAll, afterAll, beforeEach, describe, expect, it } from 'vitest';
import { PGlite } from '@electric-sql/pglite';
import { readFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
let db: PGlite;
const owner = randomUUID(), other = randomUUID();
const rpc = async (name: string, args: unknown[]) => (await db.query<{ v: any }>(`select ${name}(${args.map((_, i) => '$' + (i + 1)).join(',')}) v`, args)).rows[0].v;
const session = async () => { const id = randomUUID(); await rpc('seo_start_session', [id, '/ja/tools/remove_person', 'organic_search', 'a'.repeat(64)]); return id; };
beforeAll(async () => {
  db = new PGlite();
  await db.exec("create schema auth; create table auth.users(id uuid primary key); create role anon; create role authenticated; create role service_role bypassrls; grant usage on schema public,auth to anon,authenticated,service_role; create function auth.uid() returns uuid language sql stable as $$ select null::uuid $$;");
  for (const file of ['202610190001_web_backend.sql', '20261020153000_seo.sql', '20261020160000_seo_analytics.sql']) await db.exec(await readFile('supabase/migrations/' + file, 'utf8'));
  await db.query('insert into auth.users values($1),($2)', [owner, other]);
  await db.query("insert into seo_members values($1,'reviewer')", [owner]);
});
afterAll(() => db.close());
beforeEach(async () => { await db.exec('truncate seo_events,seo_business_links,seo_sessions,edit_jobs,orders,credit_packages,images,rate_buckets cascade'); });
describe('SEO facts use real core transaction tables in an isolated test database', () => {
  it('deduplicates events, rejects changed replay, expires and revokes consent', async () => {
    const id = await session(), event = randomUUID();
    expect(await rpc('seo_record_event', [id, event, 'page_view', '/ja', null])).toBe(true);
    expect(await rpc('seo_record_event', [id, event, 'page_view', '/ja', null])).toBe(false);
    await expect(rpc('seo_record_event', [id, event, 'tool_view', '/ja', null])).rejects.toThrow('SEO_IDEMPOTENCY_CONFLICT');
    await expect(rpc('seo_record_event', [id, randomUUID(), 'purchase_paid', '/ja', null])).rejects.toThrow('SEO_INVALID_EVENT');
    await rpc('seo_revoke_session', [id]);
    await expect(rpc('seo_record_event', [id, randomUUID(), 'page_view', '/ja', null])).rejects.toThrow('SEO_CONSENT_REQUIRED');
    expect(await rpc('seo_claim_delivery', [randomUUID(), 25])).toEqual([]);
    const expired = await session(); await db.query("update seo_sessions set expires_at=now()-interval '1 second' where id=$1", [expired]);
    await expect(rpc('seo_record_event', [expired, randomUUID(), 'page_view', '/ja', null])).rejects.toThrow('SEO_CONSENT_REQUIRED');
  });
  it('records a paid order once, includes refunds and refuses another owner', async () => {
    const id = await session(), pack = randomUUID(), order = randomUUID();
    await db.query('insert into credit_packages(id,credits,amount_minor) values($1,10,1000)', [pack]);
    await db.query("insert into orders(id,owner_id,package_id,idempotency_key,credits,amount_minor,currency) values($1,$2,$3,'seo-test-order-0001',10,1000,'JPY')", [order, owner, pack]);
    await expect(rpc('seo_link_business', [id, other, 'order', order])).rejects.toThrow('SEO_FORBIDDEN');
    await rpc('seo_link_business', [id, owner, 'order', order]);
    expect((await rpc('seo_funnel_report', [owner])).events).toEqual([]);
    await db.query("update orders set paid_at=now(),status='paid' where id=$1", [order]);
    await rpc('seo_link_business', [id, owner, 'order', order]);
    await db.query("update orders set refunded_minor=400,status='partially_refunded' where id=$1", [order]);
    const report = await rpc('seo_funnel_report', [owner]);
    expect(Number(report.events[0].event_count)).toBe(1);
    expect(Number(report.payments[0].net_jpy)).toBe(600);
    await db.query("update orders set disputed=true,status='disputed' where id=$1", [order]);
    expect(Number((await rpc('seo_funnel_report', [owner])).payments[0].net_jpy)).toBe(0);
    await expect(rpc('seo_funnel_report', [other])).rejects.toThrow('SEO_FORBIDDEN');
  });
  it('handles payment already settled before linking, and first consent wins', async () => {
    const id = await session(), later = await session(), pack = randomUUID(), order = randomUUID();
    await db.query('insert into credit_packages(id,credits,amount_minor) values($1,10,1000)', [pack]);
    await db.query("insert into orders(id,owner_id,package_id,idempotency_key,credits,amount_minor,currency,status,paid_at) values($1,$2,$3,'seo-test-order-0002',10,1000,'JPY','paid',now())", [order, owner, pack]);
    await rpc('seo_link_business', [id, owner, 'order', order]); await rpc('seo_link_business', [later, owner, 'order', order]);
    expect((await db.query<{ session_id: string }>('select session_id from seo_business_links')).rows[0].session_id).toBe(id);
    await rpc('seo_set_ga4_session',[id,'1234567890.1234567890',Math.floor(Date.now()/1000)]);
    const token = randomUUID(); const events = await rpc('seo_claim_delivery', [token, 1]);
    expect(events).toHaveLength(1); expect(await rpc('seo_claim_delivery', [randomUUID(), 25])).toEqual([]);
    await rpc('seo_finish_delivery', [events[0].id, randomUUID(), 'sent']);
    expect((await rpc('seo_funnel_report', [owner])).outbox[0].delivery_state).toBe('claimed');
    await rpc('seo_finish_delivery', [events[0].id, token, 'unknown']);
    expect((await rpc('seo_funnel_report', [owner])).outbox[0].delivery_state).toBe('unknown');
  });
  it('records core job facts, recovers a missed trigger and never rolls back payment for analytics',async()=>{
    const id=await session(),image=randomUUID(),job=randomUUID();
    await rpc('app_create_upload',[owner,image,'image/png',100,'temp/'+image,new Date(Date.now()+86400000).toISOString()]);
    await rpc('app_complete_upload',[owner,image,'fixed/'+image,'preview/'+image,'a'.repeat(64),'image/png',100,1,1]);
    await db.query("insert into edit_jobs(id,owner_id,tool_id,idempotency_key,request_hash,inputs,snapshot,credits_reserved) values($1,$2,'remove_person','seo-fact-test-0001',$3,'[]','{}',1)",[job,owner,'a'.repeat(64)]);
    await rpc('seo_link_business',[id,owner,'job',job]);
    await db.query("update edit_jobs set status='completed',result_image_id=$2 where id=$1",[job,image]);
    expect((await rpc('seo_funnel_report',[owner])).events.map((r:any)=>r.name).sort()).toEqual(['generate_success','job_create']);
    await db.query("delete from seo_events where name='generate_success'");
    expect((await rpc('seo_reconcile_business',[10])).processed).toBe(1);expect((await rpc('seo_reconcile_business',[10])).processed).toBe(0);
    const pack=randomUUID(),order=randomUUID();await db.query('insert into credit_packages(id,credits,amount_minor) values($1,10,1000)',[pack]);
    await db.query("insert into orders(id,owner_id,package_id,idempotency_key,credits,amount_minor,currency) values($1,$2,$3,'seo-test-order-failure',10,1000,'JPY')",[order,owner,pack]);
    await rpc('seo_link_business',[id,owner,'order',order]);
    await db.exec('alter table seo_events add constraint injected_analytics_failure check(false) not valid');
    await db.query("update orders set status='paid',paid_at=now()-interval '5 days' where id=$1",[order]);
    expect((await db.query<{status:string}>('select status from orders where id=$1',[order])).rows[0].status).toBe('paid');
    await db.exec('alter table seo_events drop constraint injected_analytics_failure');
    expect((await rpc('seo_reconcile_business',[10])).processed).toBe(1);
    expect((await db.query<{matches:boolean}>("select e.created_at=o.paid_at matches from seo_events e join orders o on o.id=e.entity_id where e.name='purchase_paid'")).rows[0].matches).toBe(true);
    expect((await rpc('seo_funnel_report',[owner])).events.some((r:any)=>r.name==='purchase_paid')).toBe(true);
  });
  it('enforces role boundaries and per-consent event limits', async () => {
    const id = await session(); await db.query('update seo_sessions set event_count=500 where id=$1', [id]);
    await expect(rpc('seo_record_event', [id, randomUUID(), 'page_view', '/ja', null])).rejects.toThrow('SEO_RATE_LIMITED');
    await db.exec('set role authenticated'); await expect(db.query('select * from seo_events')).rejects.toThrow('permission denied');
    await expect(rpc('seo_start_session', [randomUUID(), '/ja', 'direct', 'b'.repeat(64)])).rejects.toThrow('permission denied'); await db.exec('reset role');
  });
});
